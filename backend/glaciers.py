# ============================================================
# HELPER FUNCTIONS
# ============================================================

def get_glacier(glacier_id):
    """
    Return the configuration for a glacier.
    """

    if glacier_id not in GLACIERS:
        raise ValueError(
            f"Unknown glacier '{glacier_id}'. "
            f"Available glaciers: {', '.join(GLACIERS.keys())}"
        )

    return GLACIERS[glacier_id]


def get_study_area(glacier_id):
    """
    Create the Earth Engine study area for a glacier.
    """

    glacier = get_glacier(glacier_id)

    centre = ee.Geometry.Point(glacier["centre"])

    return centre.buffer(glacier["study_radius_m"])


def get_reference_geometry(glacier_id):
    """
    Create the Earth Engine MultiPolygon containing the
    manually selected reference areas for a glacier.
    """

    glacier = get_glacier(glacier_id)

    return ee.Geometry.MultiPolygon(
        glacier["reference_polygons"]
    )